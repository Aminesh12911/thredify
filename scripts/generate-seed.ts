// Generates supabase/seed.sql from the app's seed products so the two never drift.
// Run: npm run db:seed-sql
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { seedProducts } from "../src/lib/products/seed";

const uuid = (key: string) => {
  const h = createHash("sha1").update(`threadify:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

const categories = [...new Set(seedProducts.map((p) => p.category))];
const out: string[] = ["-- GENERATED by scripts/generate-seed.ts — do not edit by hand.", "-- Fictional demo catalogue. Safe to re-run.", ""];

out.push("insert into public.categories (id, name, slug) values");
out.push(categories.map((c) => `  (${q(uuid("cat:" + c))}, ${q(c)}, ${q(slug(c))})`).join(",\n"));
out.push("on conflict (slug) do nothing;", "");

out.push("insert into public.products (id, slug, name, description, price_inr, category_id, style, slogan, colors, featured, created_at) values");
out.push(
  seedProducts
    .map(
      (p) =>
        `  (${q(uuid("prod:" + p.slug))}, ${q(p.slug)}, ${q(p.name)}, ${q(p.description)}, ${p.price}, ${q(uuid("cat:" + p.category))}, ${q(p.style)}, ${q(p.slogan)}, ${q(JSON.stringify(p.colors))}::jsonb, ${p.featured}, ${q(p.createdAt)})`
    )
    .join(",\n")
);
out.push("on conflict (slug) do nothing;", "");

out.push("insert into public.inventory (product_id, size, stock) values");
const rows: string[] = [];
for (const p of seedProducts) {
  const per = Math.floor(p.stock / p.sizes.length);
  p.sizes.forEach((s, i) => rows.push(`  (${q(uuid("prod:" + p.slug))}, ${q(s)}, ${per + (i === 0 ? p.stock - per * p.sizes.length : 0)})`));
}
out.push(rows.join(",\n"));
out.push("on conflict (product_id, size) do nothing;", "");

writeFileSync("supabase/seed.sql", out.join("\n"));
console.log(`Wrote supabase/seed.sql (${seedProducts.length} products, ${rows.length} inventory rows)`);
